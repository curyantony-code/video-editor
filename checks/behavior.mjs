// Behavior: every feature's main path, through the packaged release.
import { startRuntime, expect } from '/home/user/oss-new/control/runtime/index.mjs';
import { png, wav, emailOf, createProject } from './fixtures.mjs';
import { fakeAi } from './fake-ai.mjs';
import { writeFile, mkdtemp } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

const step = (name) => console.log(`- ${name}`);
const runtime = await startRuntime(fakeAi);
try {
  const dir = await mkdtemp(path.join(tmpdir(), 'checks-'));
  const imageFile = path.join(dir, 'harbor-sunrise.png');
  const audioFile = path.join(dir, 'gulls.wav');
  await writeFile(imageFile, png(640, 360));
  await writeFile(audioFile, wav(2));
  const memberEmail = await emailOf(runtime, 'member');

  const owner = await (await runtime.context('owner')).newPage();
  owner.setDefaultTimeout(20000);

  step('F001 projects: create, list, rename');
  const projectId = await createProject(owner, 'Harbor Morning Walk', { expect });
  await runtime.assertBackLink(owner);
  await owner.goto('/');
  await expect(owner.getByTestId('project-card').filter({ hasText: 'Harbor Morning Walk' })).toContainText('16:9');
  const scratch = await createProject(owner, 'Scratch reel', { expect });
  await owner.goto(`/projects/${scratch}/settings`);
  await owner.getByTestId('project-rename').fill('Scratch reel v2');
  await owner.getByTestId('save-rename').click();
  await expect(owner.getByRole('heading', { level: 1, name: 'Scratch reel v2' })).toBeVisible();
  await owner.getByTestId('delete-project').click();
  await Promise.all([owner.waitForURL((u) => u.pathname === '/'), owner.getByRole('button', { name: 'Delete project' }).click()]);
  await expect(owner.getByTestId('project-card')).toHaveCount(1);

  step('F001 media: upload with measurements, list, preview, file route');
  await owner.goto(`/projects/${projectId}/media`);
  await owner.getByTestId('media-input').setInputFiles([imageFile, audioFile]);
  const imageItem = owner.getByTestId('media-item').filter({ hasText: 'harbor-sunrise.png' });
  const audioItem = owner.getByTestId('media-item').filter({ hasText: 'gulls.wav' });
  await expect(imageItem).toContainText('640×360');
  await expect(audioItem).toContainText('0:02');
  await expect(audioItem.getByTestId('media-kind')).toHaveText('Audio');
  const imageId = await imageItem.getAttribute('data-id');
  const file = await runtime.fetch(`/api/media/${imageId}`, { role: 'owner' });
  expect(file.status).toBe(200);
  expect(file.headers.get('content-type')).toBe('image/png');
  expect((await file.arrayBuffer()).byteLength).toBe(png(640, 360).length);
  await imageItem.getByTestId('preview-media').click();
  await expect(owner.getByRole('dialog').locator('img')).toBeVisible();
  await owner.keyboard.press('Escape');

  step('F003 media notes: write, draft with AI, search');
  await audioItem.getByTestId('media-note').fill('Gulls calling over the water, good under the opening');
  await audioItem.getByTestId('save-note').click();
  await expect(audioItem.getByTestId('note-saved')).toBeVisible();
  await imageItem.getByTestId('draft-note').click();
  await expect(imageItem.getByTestId('media-note')).toHaveValue(/Pier at sunrise/);
  await imageItem.getByTestId('save-note').click();
  await expect(imageItem.getByTestId('note-saved')).toBeVisible();
  await owner.getByTestId('media-search').fill('boats moored');
  await expect(owner.getByTestId('media-item')).toHaveCount(1);
  await expect(owner.getByTestId('media-item')).toContainText('harbor-sunrise.png');
  await owner.getByTestId('media-search').fill('');
  await expect(owner.getByTestId('media-item')).toHaveCount(2);

  step('F004 script: AI draft, accept, edit, reorder, save');
  await owner.goto(`/projects/${projectId}/script`);
  await owner.getByTestId('script-brief').fill('A calm one-minute film about a harbor town waking up');
  await owner.getByTestId('draft-script').click();
  await expect(owner.getByTestId('suggestion')).toContainText('EXT. HARBOR - DAWN');
  await owner.getByTestId('accept-suggestion').click();
  await expect(owner.getByTestId('scene')).toHaveCount(2);
  await owner.getByTestId('add-scene').click();
  await owner.getByTestId('scene').nth(2).getByTestId('scene-heading').fill('EXT. LIGHTHOUSE - DAY');
  await owner.getByTestId('scene').nth(2).getByTestId('scene-action').fill('The lighthouse keeper waves from the gallery.');
  await owner.getByTestId('scene').nth(2).getByTestId('scene-up').click();
  await expect(owner.getByTestId('scene').nth(1).getByTestId('scene-heading')).toHaveValue('EXT. LIGHTHOUSE - DAY');
  await owner.getByTestId('scene').nth(0).getByTestId('rewrite-scene').click();
  await owner.getByTestId('rewrite-instruction').fill('Add the gulls');
  await owner.getByTestId('run-rewrite').click();
  await expect(owner.getByTestId('suggestion')).toContainText('Gulls circle the boats');
  await owner.getByTestId('accept-suggestion').click();
  await expect(owner.getByTestId('scene').nth(0).getByTestId('scene-action')).toHaveValue(/Gulls circle/);
  await expect(owner.getByTestId('runtime-estimate')).toContainText(/\d+:\d\d/);
  await owner.getByTestId('save-script').click();
  await expect(owner.getByTestId('script-saved')).toBeVisible();
  await owner.reload();
  await expect(owner.getByTestId('scene')).toHaveCount(3);
  await expect(owner.getByTestId('scene').nth(1).getByTestId('scene-heading')).toHaveValue('EXT. LIGHTHOUSE - DAY');

  step('F005 storyboard: AI breakdown, add shot, reorder, total, send to timeline');
  await owner.goto(`/projects/${projectId}/storyboard`);
  await owner.getByTestId('breakdown').click();
  await expect(owner.getByTestId('breakdown-review')).toContainText('A vendor stacks oranges');
  await owner.getByTestId('save-breakdown').click();
  await expect(owner.getByTestId('shot')).toHaveCount(2);
  await owner.getByTestId('add-shot').click();
  await owner.getByTestId('shot-description').fill('The lighthouse from the water');
  await owner.getByTestId('shot-framing').click();
  await owner.getByRole('option', { name: 'Overhead' }).click();
  await owner.getByTestId('shot-move').fill('drone push in');
  await owner.getByTestId('shot-duration').fill('5');
  await owner.getByTestId('shot-image').setInputFiles(imageFile);
  await owner.getByTestId('save-shot').click();
  await expect(owner.getByTestId('shot')).toHaveCount(3);
  await expect(owner.getByTestId('shot').nth(2)).toContainText('Overhead');
  await expect(owner.getByTestId('shot').nth(2).locator('img')).toBeVisible();
  await expect(owner.getByTestId('storyboard-total')).toContainText('0:12');
  await owner.getByTestId('shot').nth(2).getByTestId('shot-up').click();
  await expect(owner.getByTestId('shot').nth(1)).toContainText('The lighthouse from the water');
  await expect(owner.getByTestId('shot').nth(1).getByTestId('shot-number')).toHaveText('2');
  await owner.getByTestId('send-to-timeline').click();
  await expect(owner.getByTestId('sent-to-timeline')).toBeVisible();

  step('F002 timeline: tracks, clips, move, trim, split, delete, undo');
  await owner.goto(`/projects/${projectId}`);
  const textTrack = owner.getByTestId('track').filter({ has: owner.locator('[data-kind="text"]') });
  await expect(owner.getByTestId('clip')).toHaveCount(3);
  await expect(owner.getByTestId('revision')).toHaveText('Revision 1');
  await owner.getByTestId('add-track-video').click();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 2');
  await owner.getByTestId('bin-item').filter({ hasText: 'harbor-sunrise.png' }).getByTestId('add-to-timeline').click();
  await owner.getByTestId('bin-item').filter({ hasText: 'gulls.wav' }).getByTestId('add-to-timeline').click();
  await expect(owner.getByTestId('clip')).toHaveCount(5);
  await expect(owner.getByTestId('revision')).toHaveText('Revision 4');
  const audioClip = owner.locator('[data-testid="clip"][data-kind="audio"]');
  await expect(audioClip).toHaveAttribute('data-duration', '60');
  // Trim the audio clip's end by dragging its right edge to the left.
  const endHandle = audioClip.getByTestId('trim-end');
  await owner.getByTestId('timeline').scrollIntoViewIfNeeded();
  const eb = await endHandle.boundingBox();
  await owner.mouse.move(eb.x + eb.width / 2, eb.y + eb.height / 2);
  await owner.mouse.down();
  await owner.mouse.move(eb.x + eb.width / 2 - 40, eb.y + eb.height / 2, { steps: 5 });
  await owner.mouse.up();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 5');
  const trimmed = Number(await audioClip.getAttribute('data-duration'));
  expect(trimmed).toBeLessThan(60);
  // Move it right by dragging its body.
  const ab = await audioClip.boundingBox();
  await owner.mouse.move(ab.x + 10, ab.y + ab.height / 2);
  await owner.mouse.down();
  await owner.mouse.move(ab.x + 70, ab.y + ab.height / 2, { steps: 5 });
  await owner.mouse.up();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 6');
  expect(Number(await audioClip.getAttribute('data-start'))).toBeGreaterThan(0);
  // Volume on the audio clip.
  await audioClip.click();
  await owner.getByTestId('clip-volume').fill('40');
  await owner.getByTestId('apply-clip').click();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 7');
  // A text clip with its own words.
  await owner.getByTestId('add-text').click();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 8');
  await owner.getByTestId('clip-text').fill('Morning in the harbor');
  await owner.getByTestId('apply-clip').click();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 9');
  await expect(textTrack.first().getByTestId('clip').filter({ hasText: 'Morning in the harbor' })).toHaveCount(1);
  // Split the image clip at the playhead, set by clicking the ruler.
  const imageClip = owner.locator('[data-testid="clip"][data-kind="video"]').first();
  await owner.getByTestId('timeline').scrollIntoViewIfNeeded();
  const ib = await imageClip.boundingBox();
  const ruler = await owner.getByTestId('ruler').boundingBox();
  await owner.mouse.click(ib.x + ib.width / 2, ruler.y + ruler.height / 2);
  await expect(owner.getByTestId('playhead-time')).not.toHaveText('0:00.00');
  await imageClip.click();
  await owner.getByTestId('split-clip').click();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 10');
  await expect(owner.locator('[data-testid="clip"][data-kind="video"]')).toHaveCount(2);
  await owner.getByTestId('undo').click();
  await expect(owner.getByTestId('revision')).toHaveText('Revision 11');
  await expect(owner.locator('[data-testid="clip"][data-kind="video"]')).toHaveCount(1);
  await owner.locator('[data-testid="clip"][data-kind="video"]').click();
  await owner.getByTestId('split-clip').click();
  await expect(owner.locator('[data-testid="clip"][data-kind="video"]')).toHaveCount(2);
  await owner.locator('[data-testid="clip"][data-kind="video"]').nth(1).click();
  await owner.getByTestId('delete-clip').click();
  await expect(owner.locator('[data-testid="clip"][data-kind="video"]')).toHaveCount(1);
  await owner.getByTestId('play').click();
  await expect(owner.getByTestId('playhead-time')).not.toHaveText('0:00.00');
  await owner.getByTestId('play').click();
  await owner.reload();
  await expect(owner.locator('[data-testid="clip"][data-kind="video"]')).toHaveCount(1);
  await expect(owner.getByTestId('clip').filter({ hasText: 'Morning in the harbor' })).toHaveCount(1);

  step('F003 agent: request, operations, revert');
  const clipsBefore = await owner.getByTestId('clip').count();
  await owner.getByTestId('agent-input').fill('put a title card first');
  await owner.getByTestId('agent-send').click();
  await expect(owner.getByTestId('agent-message').last()).toContainText('Added a title card at the start.');
  await expect(owner.getByTestId('agent-ops').last()).toContainText('Add text');
  await expect(owner.getByTestId('clip')).toHaveCount(clipsBefore + 1);
  const afterAgent = await owner.getByTestId('revision').textContent();
  await owner.getByTestId('agent-revert').last().click();
  await expect(owner.getByTestId('clip')).toHaveCount(clipsBefore);
  await expect(owner.getByTestId('revision')).not.toHaveText(afterAgent);
  await owner.reload();
  await expect(owner.getByTestId('agent-message').filter({ hasText: 'put a title card first' })).toHaveCount(1);

  step('F006 sharing, presence, live changes, comments');
  await owner.goto(`/projects/${projectId}/settings`);
  await owner.getByTestId('share-email').fill(memberEmail);
  await owner.getByTestId('share-add').click();
  await expect(owner.getByTestId('share-member').filter({ hasText: memberEmail })).toContainText('Editor');
  const member = await (await runtime.context('member')).newPage();
  member.setDefaultTimeout(20000);
  await member.goto('/');
  await expect(member.getByTestId('project-card').filter({ hasText: 'Harbor Morning Walk' })).toBeVisible();
  await owner.goto(`/projects/${projectId}`);
  await member.goto(`/projects/${projectId}`);
  await expect(member.getByTestId('presence')).toContainText('owner');
  await expect(owner.getByTestId('presence')).toContainText('member');
  const tracksBefore = await member.getByTestId('track').count();
  await owner.getByTestId('add-track-audio').click();
  await expect(member.getByTestId('track')).toHaveCount(tracksBefore + 1);
  await member.getByTestId('comment-input').fill('Hold on the boats a little longer here');
  await member.getByTestId('add-comment').click();
  const comment = owner.getByTestId('comment').filter({ hasText: 'Hold on the boats' });
  await expect(comment).toBeVisible();
  await comment.getByTestId('reply-toggle').click();
  await comment.getByTestId('reply-input').fill('Agreed, I will extend it');
  await comment.getByTestId('send-reply').click();
  await expect(comment).toContainText('Agreed, I will extend it');
  await comment.getByTestId('resolve-comment').click();
  await expect(comment).toContainText('Resolved');

  step('F007 export: MP4, editable project files');
  await owner.goto(`/projects/${projectId}/exports`);
  await owner.getByTestId('export-mp4').click();
  await expect(owner.getByTestId('export-item')).toHaveCount(1, { timeout: 120000 });
  const href = await owner.getByTestId('export-download').getAttribute('href');
  expect(href.startsWith('/') || new URL(href).hostname === runtime.hostname).toBe(true);
  const mp4 = await runtime.fetch(new URL(href, `https://${runtime.hostname}`).pathname, { role: 'member' });
  expect(mp4.status).toBe(200);
  expect(mp4.headers.get('content-type')).toBe('video/mp4');
  const mp4Bytes = Buffer.from(await mp4.arrayBuffer());
  expect(mp4Bytes.subarray(4, 8).toString('ascii')).toBe('ftyp');
  const otio = await runtime.fetch(`/api/projects/${projectId}/timeline.otio`, { role: 'owner' });
  expect(otio.status).toBe(200);
  const otioJson = await otio.json();
  expect(otioJson.OTIO_SCHEMA).toBe('Timeline.1');
  expect(JSON.stringify(otioJson)).toContain('harbor-sunrise.png');
  const xml = await runtime.fetch(`/api/projects/${projectId}/timeline.xml`, { role: 'member' });
  expect(xml.status).toBe(200);
  const xmlText = await xml.text();
  expect(xmlText).toContain('<xmeml');
  expect(xmlText).toContain('gulls.wav');
  const [download] = await Promise.all([owner.waitForEvent('download'), owner.getByTestId('download-zip').click()]);
  expect(download.suggestedFilename()).toMatch(/\.zip$/);

  step('F006 review link: visitor plays export and comments');
  await owner.goto(`/projects/${projectId}/settings`);
  await owner.getByTestId('create-review-link').click();
  const reviewUrl = await owner.getByTestId('review-link').textContent();
  const reviewPath = new URL(reviewUrl).pathname;
  expect(new URL(reviewUrl).hostname).toBe(runtime.hostname);
  const visitor = await (await runtime.context(null)).newPage();
  await visitor.goto(reviewPath);
  await expect(visitor.getByRole('heading', { name: 'Harbor Morning Walk' })).toBeVisible();
  await expect(visitor.getByTestId('review-video')).toHaveAttribute('src', /\/video$/);
  await visitor.getByTestId('review-name').fill('Dana from the tourism office');
  await visitor.getByTestId('review-comment').fill('Lovely light in the opening shot');
  await visitor.getByTestId('review-submit').click();
  await expect(visitor.getByTestId('review-comment-item')).toContainText('Lovely light in the opening shot');
  const video = await runtime.fetch(`${reviewPath}/video`);
  expect(video.status).toBe(200);
  await owner.goto(`/projects/${projectId}`);
  await expect(owner.getByTestId('comment').filter({ hasText: 'Lovely light' })).toContainText('Dana from the tourism office');

  step('Screenshot of the editor');
  await owner.getByTestId('clip').first().click();
  await runtime.screenshot(owner);

  step('Phone-sized smoke');
  const phone = await (await runtime.context('owner', { viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true })).newPage();
  await phone.goto('/');
  await expect(phone.getByTestId('project-card').first()).toBeVisible();
  await phone.goto(`/projects/${projectId}`);
  await expect(phone.getByRole('heading', { level: 1, name: 'Harbor Morning Walk' })).toBeVisible();
  await expect(phone.getByTestId('timeline')).toBeVisible();
  console.log('behavior: ok');
} finally {
  await runtime.close();
}
